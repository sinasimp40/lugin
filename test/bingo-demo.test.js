'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {createDemoRoom,snapshot,start,next,example}=require('../src/bingo-demo-routes');
test('HTML sample uses the real Bingo engine and gives two winning cards twice the share of one',t=>{
  const room=createDemoRoom();t.after(()=>room.db.close());
  example(room);
  let state=snapshot(room);
  assert.equal(state.states[0].event.pot,9);
  assert.deepEqual(state.balances,{'mem-demo-pc1':95,'mem-demo-pc3':96,'mem-demo-empty':0});
  for(let i=0;i<5;i++)next(room);
  state=snapshot(room);
  assert.equal(state.states[0].event.phase,'finished');
  assert.deepEqual(state.states[0].event.winners.map(w=>[w.station,w.winningCards,w.payout]).sort(),
    [['PC 1',2,6],['PC 3',1,3]]);
  assert.deepEqual(state.balances,{'mem-demo-pc1':101,'mem-demo-pc3':99,'mem-demo-empty':0});
  assert.match(state.telegramText,/\(PC 1\) — 6\.00 points/);
  assert.match(state.telegramText,/WINNERS:\n/);
  assert.match(state.telegramText,/Username: mem-demo-pc1 \(PC 1\) — 6\.00 points/);
  assert.match(state.telegramText,/Username: mem-demo-pc3 \(PC 3\) — 3\.00 points/);
  assert.match(state.telegramText,/PLAYERS & BETS:/);
  assert.match(state.telegramText,/mem-demo-pc1 \(PC 1\) — Bet: 5 points · 5 card\(s\)/);
  assert.match(state.telegramText,/mem-demo-pc3 \(PC 3\) — Bet: 4 points · 4 card\(s\)/);
  next(room);assert.equal(snapshot(room).balances['mem-demo-pc1'],101);
});
test('sample ledgers are independent; normal joins, duplicate retries, insufficient points and refunds use production rules',t=>{
  const a=createDemoRoom(),b=createDemoRoom();t.after(()=>{a.db.close();b.db.close();});
  const event=start(a).event;
  const input={username:'mem-demo-pc1',station:'PC 1',amount:5,eventId:event.id,requestId:crypto.randomUUID()};
  a.service.join(input);a.service.join(input);
  assert.equal(snapshot(a).balances['mem-demo-pc1'],95);
  assert.equal(snapshot(b).balances['mem-demo-pc1'],100);
  assert.throws(()=>a.service.join({...input,username:'mem-demo-empty',requestId:crypto.randomUUID()}),/Not enough points/);
  a.service.cancel(event.id);
  assert.equal(snapshot(a).balances['mem-demo-pc1'],100);
  a.service.cancel(event.id);
  assert.equal(snapshot(a).balances['mem-demo-pc1'],100);
});
test('zero or one member cancels without drawing and refunds every card exactly once',t=>{
  const room=createDemoRoom();t.after(()=>room.db.close());
  start(room);next(room);
  assert.equal(snapshot(room).states[0].event.phase,'cancelled');
  assert.equal(snapshot(room).states[0].event.called.length,0);
  assert.equal(snapshot(room).balances['mem-demo-pc1'],100);
  const event=start(room).event;
  const joined=room.service.join({username:'mem-demo-pc1',station:'PC 1',amount:25,eventId:event.id,requestId:crypto.randomUUID()});
  assert.equal(joined.participant.cards.length,25);
  assert.equal(joined.participant.cardCount,25);
  next(room);
  const state=snapshot(room);
  assert.equal(state.states[0].event.phase,'cancelled');
  assert.equal(state.states[0].event.called.length,0);
  assert.equal(state.states[0].event.winners.length,0);
  assert.match(state.states[0].event.reason,/Not enough participants/);
  assert.equal(state.balances['mem-demo-pc1'],100);
  assert.equal(state.balances['mem-demo-pc3'],100);
  assert.equal(room.service.state('mem-demo-pc3').participant,null);
  assert.equal(room.service.state('mem-demo-pc1',12).participant.cards.length,13);
});
